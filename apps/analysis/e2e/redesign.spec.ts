import { expect, test } from '@playwright/test'

test('single visits, fixed playback, shared image and continuous camera modes', async ({page}) => {
  test.slow() // Real WebGL rendering and camera transitions on the same constrained Mac as the app.
  const errors: string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/?target=barnard')
  await expect(page.getByText('영상 불러오는 중…',{exact:true})).toHaveCount(0, { timeout: 60_000 })
  await expect(page.getByTestId('fixed-fps')).toHaveText('8 장/초')
  await expect(page.getByRole('button',{name:'시즌 평균',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'전체 합성',exact:true})).toHaveCount(0)
  await expect(page.locator('.scene select')).toHaveCount(0)
  const right=page.getByTestId('space-time'),left=page.getByTestId('blink-frame')
  await expect(right).toHaveAttribute('data-path-visible','true')
  await expect(right).toHaveAttribute('data-projection-visible','true')
  await page.getByLabel('3D 이동 경로',{exact:true}).uncheck()
  await expect(right).toHaveAttribute('data-path-visible','false')
  await page.getByLabel('바닥 정사영',{exact:true}).uncheck()
  await expect(right).toHaveAttribute('data-projection-visible','false')
  await page.getByLabel('3D 이동 경로',{exact:true}).check()
  await page.getByLabel('바닥 정사영',{exact:true}).check()
  await page.getByLabel('SPHEREx 영상 겹치기',{exact:true}).check()
  await expect(right).toHaveAttribute('data-image-visible','true')
  for (const zoom of [1,3,6,12]) {
    await page.getByTestId(`zoom-${zoom}`).click()
    await expect(right).toHaveAttribute('data-window-width',(await left.getAttribute('data-window-width'))!)
  }
  await page.getByRole('button',{name:'관측 9로 이동',exact:true}).click()
  await expect(right).toHaveAttribute('data-visit','8')
  await expect(left).toHaveAttribute('data-visit','8')
  await page.getByRole('button',{name:'▶ Blink',exact:true}).click()
  await page.getByTestId('los-btn').click()
  await expect(page.getByTestId('los-error')).toContainText('SPHEREx 시선과 일치')
  await expect(right).not.toHaveAttribute('data-visit','8')
  await page.getByRole('button',{name:'■ 정지',exact:true}).first().click()
  await expect(right).toHaveAttribute('data-visit',(await left.getAttribute('data-visit'))!)
  await page.waitForTimeout(1300) // let the known 1100 ms camera transition finish before the visual artifact
  await page.screenshot({path:'docs/screenshots/redesign-los.png'})
  await page.getByRole('button',{name:'← 3D로 돌아가기'}).click()
  await page.waitForTimeout(1300)
  await page.screenshot({path:'docs/screenshots/redesign-overview.png'})
  await page.getByLabel('SPHEREx 영상 겹치기',{exact:true}).uncheck()
  await expect(right).toHaveAttribute('data-image-visible','false')
  expect(errors).toEqual([])
})
