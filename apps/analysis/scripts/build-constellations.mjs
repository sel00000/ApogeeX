// Builds public/data/sky/constellations.json: constellation stick figures as RA/Dec polylines.
// Run from anywhere: node apps/analysis/scripts/build-constellations.mjs
// Inputs are read from the repository (apps/planetarium); nothing is downloaded. Output is deterministic.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..'); // repository / work tree root
const P = {
  figures: 'apps/planetarium/vendor/stellarium-web-engine/apps/test-skydata/skycultures/western/index.json',
  hip: 'apps/planetarium/catalogs/hipparcos2-astrometry.tsv.gz',
  names: 'apps/planetarium/src/constellation-names.js',
};
const out = resolve(here, '../public/data/sky/constellations.json');

const r3 = (x) => Math.round(x * 1000) / 1000;
const rad = Math.PI / 180;

// Positions: Hipparcos-2, degrees, ICRS, epoch J1991.25
const pos = new Map();
for (const line of gunzipSync(readFileSync(resolve(root, P.hip))).toString('utf8').split('\n')) {
  if (!line || line[0] === '#') continue;
  const c = line.split('\t');
  const hip = Number(c[0]);
  const ra = Number(c[1]), dec = Number(c[2]);
  if (Number.isInteger(hip) && hip > 0 && Number.isFinite(ra) && Number.isFinite(dec)) pos.set(hip, [ra, dec]);
}

const sky = JSON.parse(readFileSync(resolve(root, P.figures), 'utf8'));
const { constellationNames } = await import(pathToFileURL(resolve(root, P.names)).href);
const hangul = /[가-힣]/;
const koNames = JSON.parse(readFileSync(resolve(here, 'constellation-names-ko.json'), 'utf8'));
const koByLower = new Map(Object.keys(koNames).map((k) => [k.toLowerCase(), k]));
const renamed = [];

const missing = [];
const noKo = [];
const list = [];
for (const c of sky.constellations) {
  const rawId = c.iau;
  // The sky culture writes some ids with different letter case (Cvn, Tra); use the canonical IAU form from the Korean table.
  const id = koByLower.get(rawId.toLowerCase()) ?? rawId;
  if (id !== rawId) renamed.push(`${rawId}->${id}`);
  const en = c.common_name?.native ?? constellationNames[id] ?? id;
  const ko = koNames[id] ?? en;
  if (!ko || !hangul.test(ko)) noKo.push(id);
  const lines = [];
  const used = new Set();
  for (const l of c.lines) {
    // Drop only the segment touching an unresolved star: split the polyline there.
    let cur = [];
    const flush = () => { if (cur.length >= 2) lines.push(cur); cur = []; };
    for (const h of l) {
      const p = pos.get(h);
      if (!p) { missing.push(`${id}:${h}`); flush(); continue; }
      used.add(h);
      cur.push([r3(p[0]), r3(p[1])]);
    }
    flush();
  }
  let x = 0, y = 0, z = 0;
  for (const h of [...used].sort((a, b) => a - b)) {
    const [ra, dec] = pos.get(h);
    x += Math.cos(dec * rad) * Math.cos(ra * rad);
    y += Math.cos(dec * rad) * Math.sin(ra * rad);
    z += Math.sin(dec * rad);
  }
  let lra = Math.atan2(y, x) / rad; if (lra < 0) lra += 360;
  const ldec = Math.atan2(z, Math.hypot(x, y)) / rad;
  let label = [r3(lra), r3(ldec)];
  if (label[0] >= 360) label[0] = 0;
  list.push({ id, en, ko, label, lines });
}
list.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const data = {
  version: 1,
  source: {
    figures: 'Stellarium Web Engine sky culture "western" (apps/test-skydata/skycultures/western/index.json, in apps/planetarium/vendor/stellarium-web-engine); authors: Stellarium\'s team; licence stated in its description.md: "Text and data: CC BY-SA" (illustrations, not used here: Free Art License). The engine itself is AGPL-3.0.',
    positions: 'Hipparcos, the New Reduction (F. van Leeuwen 2007, A&A 474, 653; VizieR I/311/hip2), ICRS, epoch J1991.25, via apps/planetarium/catalogs/hipparcos2-astrometry.tsv.gz; licence reference: https://cds.unistra.fr/vizier-org/licences_vizier.html',
    names: 'en: Latin names from the western sky culture (common_name.native); ko: Korean names typed in by the AI design session from the standard Korean constellation names, without a cited source file; not yet checked by the team (apps/analysis/scripts/constellation-names-ko.json); the sky culture and apps/planetarium/src/constellation-names.js have none.',
    notes: 'Angles in degrees, ICRS, RA in [0,360), rounded to 3 decimals. Star positions are at epoch J1991.25 (Hipparcos-2); proper motion to the present day is not applied because it is far below what a stick figure needs. label is the direction of the mean unit vector of the distinct vertices. The figures are a guide drawing, not SPHEREx data. Generated by apps/analysis/scripts/build-constellations.mjs.',
  },
  constellations: list,
};

// Compact: one constellation per line, coordinate arrays unpadded.
const body = list.map((c) => '  ' + JSON.stringify(c)).join(',\n');
const head = JSON.stringify({ ...data, constellations: undefined }).slice(0, -1);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, head + ',"constellations":[\n' + body + '\n]}\n');

const distinct = new Set(list.flatMap((c) => c.lines.flat().map((p) => p.join(','))));
console.log(JSON.stringify({
  constellations: list.length,
  polylines: list.reduce((n, c) => n + c.lines.length, 0),
  distinctStarPositions: distinct.size,
  missingHip: missing,
  missingKorean: noKo,
  idsRenamedToCanonicalCase: renamed,
}));
