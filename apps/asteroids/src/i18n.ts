export const TABLES: Record<Lang, Record<Key, string>> = {en, ko};

export function readLang(): Lang {
  try { return localStorage.getItem(LANG_KEY) === 'ko' ? 'ko' : 'en'; } catch { return 'en'; }
}
let current: Lang = typeof window === 'undefined' ? 'en' : readLang();
export const lang = () => current;

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = TABLES[current][key] ?? TABLES.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

