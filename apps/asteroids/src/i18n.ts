/** Planets and the Sun get English names; asteroid designations stay as they are in the data. */
export function bodyName(body: {id: string; name: string; kind?: string}): string {
  if (body.kind === 'asteroid') return body.name;
  const key = (body.kind === 'sun' ? 'body.sun' : 'body.' + body.id) as Key;
  return key in en ? t(key) : body.name;
}

/** An Error whose message follows the current language (the message is read when it is shown). */
export class LocalError extends Error {
  constructor(readonly key: Key, readonly vars?: Record<string, string | number>) {
    super();
    Object.defineProperty(this, 'message', {get: () => t(key, vars), configurable: true});
  }
}

type Thunk = () => string;
const bindings = new Map<Element, Map<string, Thunk>>();
function bind(el: Element, slot: string, thunk: Thunk) {
  let slots = bindings.get(el);
  if (!slots) bindings.set(el, slots = new Map());
  slots.set(slot, thunk);
  write(el, slot, thunk());
}
function write(el: Element, slot: string, value: string) {
  if (slot === 'text') { if (el.textContent !== value) el.textContent = value; }
  else if (slot === 'html') { if (el.innerHTML !== value) el.innerHTML = value; }
  else if (el.getAttribute(slot) !== value) el.setAttribute(slot, value);
}
/** Sets the element's text now and again after every language switch. All writes to that element go through here. */
export const bindText = (el: Element, thunk: Thunk) => bind(el, 'text', thunk);
export const bindHtml = (el: Element, thunk: Thunk) => bind(el, 'html', thunk);
export const bindAttr = (el: Element, name: string, thunk: Thunk) => bind(el, name, thunk);

/** data-i18n (text), data-i18n-html, data-i18n-aria (aria-label), data-i18n-ph (placeholder), data-i18n-title. */
export function applyI18n(root: ParentNode = document) {
  const each = (attr: string, fn: (el: HTMLElement, key: Key) => void) =>
    root.querySelectorAll<HTMLElement>(`[${attr}]`).forEach(el => fn(el, el.getAttribute(attr) as Key));
  each('data-i18n', (el, k) => write(el, 'text', t(k)));
  each('data-i18n-html', (el, k) => write(el, 'html', t(k)));
  each('data-i18n-aria', (el, k) => write(el, 'aria-label', t(k)));
  each('data-i18n-ph', (el, k) => write(el, 'placeholder', t(k)));
  each('data-i18n-title', (el, k) => write(el, 'title', t(k)));
}

const listeners = new Set<(l: Lang) => void>();
export function onLang(fn: (l: Lang) => void) { listeners.add(fn); return () => { listeners.delete(fn); }; }

export function setLang(next: Lang) {
  current = next === 'ko' ? 'ko' : 'en';
  if (typeof document === 'undefined') { for (const fn of listeners) fn(current); return; }
  document.documentElement.lang = current;
  document.title = t('doc.title');
  applyI18n(document);
  for (const [el, slots] of bindings) {
    if (!el.isConnected) { bindings.delete(el); continue; }
    for (const [slot, thunk] of slots) write(el, slot, thunk());
  }
  for (const fn of listeners) fn(current);
}

/** D1: read at start, follow the storage event and the parent's { type: 'spherex-lang', lang } message. */
export function initLang() {
  setLang(readLang());
  window.addEventListener('storage', event => {
    if (event.key === LANG_KEY || event.key === null) { const next = readLang(); if (next !== current) setLang(next); }
  });
  window.addEventListener('message', event => {
    if (event.origin !== location.origin || event.source !== window.parent || window.parent === window) return;
    const data = event.data as {type?: unknown; lang?: unknown} | null;
    if (!data || typeof data !== 'object' || data.type !== 'spherex-lang') return;
    const next: Lang = data.lang === 'ko' ? 'ko' : 'en';
    if (next !== current) setLang(next);
  });
}
