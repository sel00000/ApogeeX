const copy = async (from, to) => {
  await mkdir(dirname(to), { recursive: true });
  await cp(from, to, { recursive: true, dereference: false });
};

// Complete source is shipped alongside the site, including the patched engine,
// its external libraries, bundled input data, and reproducible build scripts.
const sourceRoot = join(staging, 'source', 'project');
const skipNames = new Set(['.git', 'node_modules', '__pycache__', '.cache', '.sconsign.dblite', '.DS_Store']);
async function copySource(from, to) {
  const info = await stat(from);
  if (!info.isDirectory()) return copy(from, to);
  await mkdir(to, { recursive: true });
  for (const entry of await readdir(from, { withFileTypes: true })) {
    if (skipNames.has(entry.name) || (entry.isDirectory() && /^build(?:[-_.].*)?$/.test(entry.name)) || /\.(?:o|obj|pyc|log)$/.test(entry.name)) continue;
    if (entry.isSymbolicLink()) throw new Error(`Unexpected symlink in corresponding source: ${join(from, entry.name)}`);
    await copySource(join(from, entry.name), join(to, entry.name));
  }
}

const page = (title, body) => `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${escapeHtml(title)}</title><style>body{font:16px/1.6 system-ui,sans-serif;max-width:960px;margin:48px auto;padding:0 24px;background:#101925;color:#e9eef5}a{color:#82dfe6}li{margin:.25rem 0}code{overflow-wrap:anywhere}small{color:#aab8ca}h1{font-size:1.7rem}a:focus-visible{outline:2px solid #fff;outline-offset:4px}</style>${body}</html>\n`;

async function makeSourceIndex(directory) {
  const entries = (await readdir(directory, { withFileTypes: true })).filter((entry) => entry.name !== 'directory.html');
  entries.sort((a, b) => Number(b.isDirectory()) - Number(a.isDirectory()) || a.name.localeCompare(b.name));
  const items = [];
  for (const entry of entries) {
    if (entry.isDirectory()) await makeSourceIndex(join(directory, entry.name));
    const url = encodeURIComponent(entry.name) + (entry.isDirectory() ? '/directory.html' : '');
    items.push(`<li><a href="${url}"${entry.isFile() ? ' download' : ''}>${escapeHtml(entry.name)}${entry.isDirectory() ? '/' : ''}</a></li>`);
  }
  const label = relative(sourceRoot, directory).split(sep).join('/') || 'project';
  const back = directory === sourceRoot ? '../index.html' : '../directory.html';
  await writeFile(join(directory, 'directory.html'), page(`Source: ${label}`, `<a href="${back}">← Parent</a><h1>Corresponding source</h1><p><code>${escapeHtml(label)}/</code></p><p><small>File links download the original source. Folder links open its file list.</small></p><ul>${items.join('')}</ul>`));
}

// A conventional UTF-8 ZIP makes the complete source downloadable in one click.
// Small project files fit comfortably within the ordinary ZIP32 format.
async function zipSource() {
  const crcTable = Array.from({ length: 256 }, (_, value) => {
    for (let bit = 0; bit < 8; bit++) value = (value & 1) ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
    return value >>> 0;
  });
  const crc32 = (data) => {
    let crc = 0xffffffff;
    for (const byte of data) crc = crcTable[(crc ^ byte) & 255] ^ (crc >>> 8);
    return (crc ^ 0xffffffff) >>> 0;
  };
  const localRecords = [];
  const directoryRecords = [];
  let offset = 0;
  async function addFiles(directory) {
    const entries = (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name));
    for (const entry of entries) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) { await addFiles(path); continue; }
      const filename = Buffer.from('stellarium-web-lab/' + relative(sourceRoot, path).split(sep).join('/'));
      const original = await readFile(path);
      const packed = deflateRawSync(original);
      const crc = crc32(original);
      const header = Buffer.alloc(30);
      header.writeUInt32LE(0x04034b50, 0);
      header.writeUInt16LE(20, 4);
      header.writeUInt16LE(0x0800, 6);
      header.writeUInt16LE(8, 8);
      header.writeUInt16LE(0x0021, 12); // DOS date: 1980-01-01; reproducible archive.
      header.writeUInt32LE(crc, 14);
      header.writeUInt32LE(packed.length, 18);
      header.writeUInt32LE(original.length, 22);
      header.writeUInt16LE(filename.length, 26);
      const central = Buffer.alloc(46);
      central.writeUInt32LE(0x02014b50, 0);
      central.writeUInt16LE(0x0314, 4);
      central.writeUInt16LE(20, 6);
      central.writeUInt16LE(0x0800, 8);
      central.writeUInt16LE(8, 10);
      central.writeUInt16LE(0x0021, 14);
      central.writeUInt32LE(crc, 16);
      central.writeUInt32LE(packed.length, 20);
      central.writeUInt32LE(original.length, 24);
      central.writeUInt16LE(filename.length, 28);
      central.writeUInt32LE((0o100644 << 16) >>> 0, 38);
      central.writeUInt32LE(offset, 42);
      localRecords.push(header, filename, packed);
      directoryRecords.push(central, filename);
      offset += header.length + filename.length + packed.length;
    }
  }
  await addFiles(sourceRoot);
  const count = directoryRecords.length / 2;
  if (count > 65535 || offset > 0xffffffff) throw new Error('Source archive exceeds ZIP32 limits.');
  const centralDirectory = Buffer.concat(directoryRecords);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(count, 8);
  end.writeUInt16LE(count, 10);
  end.writeUInt32LE(centralDirectory.length, 12);
  end.writeUInt32LE(offset, 16);
  await writeFile(join(staging, 'source', 'stellarium-web-lab-source.zip'), Buffer.concat([...localRecords, centralDirectory, end]));
}

try {
  for (const name of ['index.html', 'README.html', 'LICENSE-AGPL-3.0.txt', 'src']) await copy(join(root, name), join(staging, name));
  for (const name of ['assets', 'NOTICE.md', 'THIRD-PARTY-NOTICES.md']) {
    if (await exists(join(root, name))) await copy(join(root, name), join(staging, name));
  }
  for (const name of engineNames) await copy(join(engineDir, name), join(staging, 'engine', name));
  if (await exists(join(engineDir, 'build-info.json'))) await copy(join(engineDir, 'build-info.json'), join(staging, 'engine', 'build-info.json'));
  await copy(join(vendor, 'apps', 'test-skydata'), join(staging, 'skydata'));
  await copy(join(vendor, 'data', 'font'), join(staging, 'fonts'));
  await writeFile(join(staging, '.nojekyll'), '');

  const sourceEntries = ['index.html', 'src', 'assets', 'scripts', 'tests', 'catalogs', 'provenance', '.github', '.gitignore', 'package.json', 'Start-Web.cmd', 'README.md', 'README.html', 'LICENSE-AGPL-3.0.txt', 'NOTICE.md', 'THIRD-PARTY-NOTICES.md', 'docs', 'engine/build-info.json'];
  for (const name of sourceEntries) if (await exists(join(root, name))) await copySource(join(root, name), join(sourceRoot, name));
  await copySource(vendor, join(sourceRoot, 'vendor', 'stellarium-web-engine'));
  await makeSourceIndex(sourceRoot);
  await zipSource();
  await writeFile(join(staging, 'source', 'index.html'), page('Stellarium Web Lab source', '<a href="../">← Back to Stellarium</a><h1>Stellarium Web Lab — corresponding source</h1><p>This site includes its application source, the full vendored Stellarium Web Engine source, bundled data, patches, and build scripts. Engine binaries are generated from this source.</p><ul><li><a href="stellarium-web-lab-source.zip" download>Download complete corresponding source (.zip)</a></li><li><a href="project/directory.html">Browse source files</a></li><li><a href="project/README.md" download>Build and deployment instructions</a></li><li><a href="../LICENSE-AGPL-3.0.txt">GNU Affero General Public License</a></li></ul><p>The original engine is maintained by <a href="https://github.com/Stellarium/stellarium-web-engine">Stellarium</a>. This project is a separate application using that engine.</p>'));
  await writeFile(join(staging, marker), JSON.stringify({ project: 'stellarium-web-lab', version: '5.0.0', builtAt: new Date().toISOString() }, null, 2) + '\n');
  // Both paths are fixed direct children of the project root. Only this build's
  // marked dist folder is replaced, after all inputs have copied successfully.
  if (await exists(output)) await rm(output, { recursive: true });
  // Windows file indexing can briefly hold the completed directory open.
  for (let attempt = 0; ; attempt++) {
    try { await rename(staging, output); break; }
    catch (error) {
      if (!['EPERM', 'EBUSY', 'EACCES'].includes(error.code) || attempt >= 5) throw error;
      await delay(100 * 2 ** attempt);
    }
  }
  let bytes = 0;
  let files = 0;
  async function count(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await count(path);
      else { files++; bytes += (await stat(path)).size; }
    }
  }
  await count(output);
  console.log(`Built dist/: ${files} files, ${(bytes / 1024 / 1024).toFixed(1)} MiB.\nPublish the contents of dist/. Preview: npm run preview`);
} catch (error) {
  console.error(`Build failed. The unfinished output is retained for inspection at ${staging}`);
  throw error;
}
